<?php
/**
 * Regenerate tests/visual/index.html from the fixtures and the real Renderer.
 *
 * Needs WordPress loaded, e.g. from the dev site (bin/dev-site.sh once):
 *   vendor/bin/wp --path=vendor/johnpbloch/wordpress-core --allow-root eval-file tests/visual/build.php
 *
 * @package Gistful
 */

use Gistful\Attributes;
use Gistful\Gist_Payload;
use Gistful\Renderer;

$fixture = static function ( string $name ): string {
	return (string) json_decode( (string) file_get_contents( GISTFUL_DIR . 'tests/fixtures/' . $name ) )->div;
};

$sections = array(
	'light' => 'data-scheme=light',
	'dark'  => 'data-scheme=dark',
	'auto'  => 'data-scheme=auto (follows the OS)',
);

$cols = '';
foreach ( $sections as $scheme => $title ) {
	// Renderer::render() is the real path: sanitizer, line logic and the .gistful scheme wrapper.
	$html  = Renderer::render(
		new Gist_Payload( $fixture( 'json-single.json' ), array(), 'json' ),
		Attributes::normalize(
			array(
				'id'        => 'a',
				'lines'     => '1-14',
				'highlight' => '3,6',
				'scheme'    => $scheme,
			)
		)
	);
	$html .= Renderer::render(
		new Gist_Payload( $fixture( 'json-multi.json' ), array(), 'json' ),
		Attributes::normalize(
			array(
				'id'     => 'b',
				'lines'  => '1-8',
				'scheme' => $scheme,
			)
		)
	);
	$cls   = 'dark' === $scheme ? 'd' : 'l';
	$cols .= "<section class=\"col $cls\"><h2>$title</h2>\n$html\n</section>\n";
}

$page = <<<HTML
<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Gistful visual check</title>
<link rel="stylesheet" href="../../assets/css/gistful.css">
<style>body{font:14px/1.5 system-ui,sans-serif;margin:16px}.cols{display:grid;grid-template-columns:repeat(auto-fit,minmax(360px,1fr));gap:16px}.col{padding:12px;border-radius:6px}.col.l{background:#fff;color:#1f2328}.col.d{background:#010409;color:#e6edf3}h2{margin-top:0;font-size:16px}</style></head><body>
<h1>Gistful visual check</h1><p>Generated by tests/visual/build.php. Flip the OS between light and dark: the auto column must follow it, the others must not. Check readability, highlighted lines 3 and 6 of the first gist (CSS variable highlight, no inline style), and horizontal scroll on narrow widths.</p>
<div class="cols">
$cols</div></body></html>

HTML;

file_put_contents( GISTFUL_DIR . 'tests/visual/index.html', $page ); // phpcs:ignore WordPress.WP.AlternativeFunctions
echo 'Wrote tests/visual/index.html (' . strlen( $page ) . " bytes)\n"; // phpcs:ignore WordPress.Security.EscapeOutput
